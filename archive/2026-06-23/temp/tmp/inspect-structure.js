const { chromium } = require("playwright");
const path = require("path");
(async () => {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ storageState: path.join(process.cwd(), "storageState.json") });
  const page = await context.newPage();
  await page.goto("https://distribuciongastos.pacificotest.com.pe/distribuciones/", { waitUntil: 'domcontentloaded'});
  await page.waitForSelector('h1:has-text("Distribuciones")', { timeout: 30000 });
  await page.waitForTimeout(3000);
  console.log('page title', await page.title());
  console.log('body length', await page.locator('body').evaluate(el => el.innerHTML.length));
  const tableCount = await page.locator('table').count();
  console.log('tables', tableCount);
  const rowCount = await page.locator('[role="row"]').count();
  console.log('role rows', rowCount);
  const trs = await page.locator('tr').count();
  console.log('tr count', trs);
  const th = await page.locator('th').count();
  console.log('th count', th);
  const tableOuter = await page.locator('table').first().evaluate(el => el.outerHTML.slice(0, 500)).catch(() => 'none');
  console.log('tableOuter', tableOuter);
  const rowsOuter = await page.locator('[role="row"]').first().evaluate(el => el.outerHTML.slice(0,500)).catch(() => 'none');
  console.log('rowOuter', rowsOuter);
  const ay = await page.locator('div[role="row"]').count();
  console.log('div rows', ay);
  const possibleRows = await page.locator('div').filter({ hasText: /Creada|Real/ }).count();
  console.log('possible rows containers with text Creada|Real', possibleRows);
  await page.screenshot({ path: 'tmp/distribuciones-debug.png', fullPage: true });
  await browser.close();
})();
