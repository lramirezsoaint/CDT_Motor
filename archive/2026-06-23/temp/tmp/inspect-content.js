const { chromium } = require("playwright");
const path = require("path");
(async () => {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ storageState: path.join(process.cwd(), "storageState.json") });
  const page = await context.newPage();
  await page.goto("https://distribuciongastos.pacificotest.com.pe/distribuciones/", { waitUntil: 'domcontentloaded'});
  await page.waitForTimeout(10000);
  const content = await page.content();
  const hasTable = content.includes('<table');
  const hasDataSlot = content.includes('data-slot');
  console.log('hasTable', hasTable);
  console.log('hasDataSlot', hasDataSlot);
  const idx = content.indexOf('data-slot="table"');
  console.log('table data-slot idx', idx);
  if (idx !== -1) console.log(content.slice(idx, idx+200));
  const idx2 = content.indexOf('data-slot="table-row"');
  console.log('table-row idx', idx2);
  if (idx2 !== -1) console.log(content.slice(idx2, idx2+200));
  await browser.close();
})();
